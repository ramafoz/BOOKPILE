export type CatalogueCopyKey = keyof typeof en;
export type CatalogueCopy = (key: CatalogueCopyKey, values?: Record<string, string | number>) => string;





const catalogues: Partial<Record<AppLocale, Record<CatalogueCopyKey, string>>> = { en };

export function registerCatalogueCatalogue(
  locale: AppLocale,
  catalogue: Record<CatalogueCopyKey, string>,
): void {
  catalogues[locale] = catalogue;
}

export function catalogueCopy(locale: AppLocale): CatalogueCopy {
  const catalogue = catalogues[locale];
  if (!catalogue) throw new Error(`Locale catalogue not loaded: ${locale}`);
  return (key, values = {}) => catalogue[key].replace(/\{(\w+)\}/g, (token, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : token,
  );
}
